#!/usr/bin/env bash
# Line coverage per codebase (global rule #29), the gate's coverage step (gate-core.sh runs this file).
#
# Exit codes:  0  every codebase that exists is measured and at or above the threshold
#              1  the tests are red, or a measured codebase is below the threshold
#              3  a codebase exists but is NOT measured — which blocks, exactly like a failure
#                 (#29: an unmeasured codebase does not count as passing)
#
# The codebases (ADR-0002): the .NET API, the .NET agent and the web app, each measured on its own.
#
# TWO WAYS OF WORKING, one verdict:
#   standalone  (bash scripts/coverage.sh)  runs the tests itself, with coverage on, and judges the numbers.
#   reuse       (COVERAGE_REUSE=1 and COVERAGE_DIR, set by scripts/merge-gate.conf for a gate run) runs NO test: the
#               gate's unit-test step already ran them once with coverage collected into COVERAGE_DIR, and this reads
#               those files. A missing or unreadable result is "NOT MEASURED" (exit 3), never a pass.
# Collection is the test projects' own business (tests/coverage.props, web/vite.config.ts); this file only judges.
#
# THE EXCLUSION LIST (global #29: generated code only, one place, a reason per entry):
#   .NET: tests/coverage.props   **/Data/Migrations/*.cs (EF Core migrations and the model snapshot, generated by
#                                `dotnet ef`) and **/obj/**/*.cs (source generators' output, the [GeneratedRegex]
#                                implementations); the measured assemblies are each test project's Include property.
#   web:  web/vite.config.ts     the tests and their helpers, the mount-only entry point, type declarations.
#   tests/**                     the tests themselves are not measured (they are the measurement).
#
# Out of scope, stated: the scripts under scripts/ are gate tooling, not product. The shared ones are measured in
# the configuration repository; this repository's own (backcompat_scan.py) is tested here. Their tests
# (scripts/tests) run, and red blocks.
set -uo pipefail

root="$(git rev-parse --show-toplevel 2>/dev/null)" || { echo "not inside a git repository" >&2; exit 2; }
cd "$root" || exit 2
min="${COVERAGE_MIN:-80}"
status=0
reuse=0
if [ "${COVERAGE_REUSE:-}" = 1 ] && [ -n "${COVERAGE_DIR:-}" ]; then reuse=1; else unset COVERAGE_DIR; fi
worse() { if [ "$1" != 0 ] && { [ "$status" = 0 ] || [ "$1" = 3 ]; }; then status="$1"; fi; }

echo "▶ gate tool tests (scripts/tests)"
log="$(mktemp)"
if python3 -m unittest discover -s scripts/tests -p 'test_*.py' >"$log" 2>&1; then
  echo "  ✓ $(grep -E '^Ran ' "$log")"
else
  tail -20 "$log" | sed 's/^/  /'
  echo "  ✗ the tests are red"
  worse 1
fi
rm -f "$log"
find scripts -name __pycache__ -prune -exec rm -rf {} + 2>/dev/null

# Covered and total lines out of a coverage result, "covered total" on stdout; exit 1 when the file is missing, unreadable
# or measures nothing. kind: cobertura (coverlet, .NET) or summary (vitest json-summary, web).
read_lines() {
  python3 - "$1" "$2" <<'PY'
import json
import sys
import xml.etree.ElementTree as ET

kind, path = sys.argv[1], sys.argv[2]
try:
    if kind == "cobertura":
        root = ET.parse(path).getroot()
        covered, total = int(root.attrib["lines-covered"]), int(root.attrib["lines-valid"])
    else:
        with open(path, encoding="utf-8") as handle:
            lines = json.load(handle)["total"]["lines"]
        covered, total = int(lines["covered"]), int(lines["total"])
except (OSError, ValueError, KeyError, TypeError, ET.ParseError):
    sys.exit(1)
if total <= 0 or covered < 0 or covered > total:
    sys.exit(1)
print(covered, total)
PY
}

# Judge one codebase's numbers: prints the line figure, sets the status. Exact arithmetic (covered*100 >= min*total),
# never a rounded percentage, so 79.96% cannot pass as 80.
judge() { # judge <covered> <total>
  local pct; pct="$(awk -v c="$1" -v t="$2" 'BEGIN { printf "%.2f", c * 100 / t }')"
  echo "  Lines: ${pct}% ($1/$2)"
  if awk -v c="$1" -v t="$2" -v m="$min" 'BEGIN { exit !(c * 100 >= m * t) }'; then echo "  ✓ at or above ${min}%"
  else echo "  ✗ below ${min}%"; worse 1; fi
}

# One .NET codebase: its test project (the assemblies it measures are that project's Include, tests/coverage.props).
# The API's tests start PostgreSQL in Docker.
dotnet_codebase() {
  local label="$1" tests="$2" result figures
  echo "▶ .NET: $label (threshold ${min}%)"
  result="${COVERAGE_DIR:-}/$(basename "$tests")/coverage.cobertura.xml"
  if [ "$reuse" = 1 ]; then
    if [ ! -f "$result" ]; then echo "  NOT MEASURED: the unit-test step left no coverage result for $tests ($result)"; worse 3; return; fi
  else
    if ! command -v dotnet >/dev/null 2>&1; then echo "  NOT MEASURED: dotnet is not installed"; worse 3; return; fi
    if [ ! -d "$tests" ]; then echo "  NOT MEASURED: $tests is missing"; worse 3; return; fi
    if [ "$label" = "API" ] && ! docker info >/dev/null 2>&1; then
      echo "  NOT MEASURED: Docker is not running (the API's tests need a real PostgreSQL)"; worse 3; return
    fi
    local out dir; out="$(mktemp)"; dir="$(mktemp -d)"
    result="$dir/$(basename "$tests")/coverage.cobertura.xml"
    if ! COVERAGE_DIR="$dir" dotnet test "$tests" --nologo >"$out" 2>&1; then
      grep -E 'Failed |error|Passed!|Failed!' "$out" | head -20 | sed 's/^/  /'
      echo "  ✗ the tests are red or did not build"; worse 1; rm -rf "$out" "$dir"; return
    fi
    rm -f "$out"
  fi
  if figures="$(read_lines cobertura "$result")"; then
    # shellcheck disable=SC2086  # "covered total": two words, split on purpose
    judge $figures
  else
    echo "  NOT MEASURED: $result is missing, unreadable or measures no line"; worse 3
  fi
  [ "$reuse" = 1 ] || rm -rf "${dir:-}"
}

if [ -z "$(git ls-files --cached --others --exclude-standard '*.csproj')" ]; then
  echo "▶ .NET"
  echo "  n/a: no .NET project yet"
else
  dotnet_codebase "API" tests/ClaudeMonitor.Api.Tests
  dotnet_codebase "agent" tests/ClaudeMonitor.Agent.Tests
fi

echo "▶ web (threshold ${min}%)"
if [ -z "$(git ls-files --cached --others --exclude-standard 'web/package.json')" ]; then
  echo "  n/a: no web app yet"
elif [ "$reuse" = 1 ]; then
  if figures="$(read_lines summary "$COVERAGE_DIR/web/coverage-summary.json")"; then
    # shellcheck disable=SC2086  # "covered total": two words, split on purpose
    judge $figures
  else
    echo "  NOT MEASURED: the unit-test step left no readable coverage result for the web app ($COVERAGE_DIR/web/coverage-summary.json)"
    worse 3
  fi
elif ! command -v npm >/dev/null 2>&1; then
  echo "  NOT MEASURED: npm is not installed"
  worse 3
else
  # The threshold and the exclusion list (tests, the mount-only entry point, type declarations) are in
  # web/vite.config.ts; vitest exits non-zero below it.
  web_log="$(mktemp)"
  if { [ -d web/node_modules ] || npm --prefix web ci --silent >"$web_log" 2>&1; } \
     && CI=true npm --prefix web run coverage -- --coverage.thresholds.lines="$min" >"$web_log" 2>&1; then
    grep -E '^(Lines|Statements)' "$web_log" | sed 's/^/  /'
    echo "  ✓ at or above ${min}%"
  else
    grep -E 'Tests |FAIL|ERROR|Lines|threshold' "$web_log" | head -15 | sed 's/^/  /'
    echo "  ✗ the tests are red or below ${min}%"
    worse 1
  fi
  rm -f "$web_log"
fi

# A gate run made COVERAGE_DIR itself (merge-gate.conf); its results are consumed, so it goes.
[ "$reuse" = 1 ] && [ "${COVERAGE_DIR_OWNED:-}" = 1 ] && rm -rf "$COVERAGE_DIR"

exit "$status"
